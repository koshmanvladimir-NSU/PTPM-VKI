"""
Лабораторная работа №1. Вариант 1.
Вычисление вида треугольника и координат его вершин.
"""

import os
import math
import logging


# --------------------------------------------------------------------------
# 1. НАСТРОЙКА ЛОГИРОВАНИЯ
# --------------------------------------------------------------------------

def setup_logging():
    """Настраивает вывод логов одновременно в консоль и в файл logs/file_txt.log"""
    os.makedirs("logs", exist_ok=True)

    log_format = "%(asctime)s | [%(levelname)-7s] | %(message)s"
    date_format = "%Y-%m-%d %H:%M:%S"

    logging.basicConfig(
        level=logging.DEBUG,
        format=log_format,
        datefmt=date_format,
        handlers=[
            logging.StreamHandler(),
            logging.FileHandler("logs/file_txt.log", encoding="utf-8"),
        ],
    )


# --------------------------------------------------------------------------
# 2. ПАРСИНГ ВХОДНЫХ ДАННЫХ
# --------------------------------------------------------------------------

def parse_side(value: str):
    """
    Пытается превратить строку в float.
    Возвращает число, либо None, если строка не является
    корректным вещественным числом.
    """
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


# --------------------------------------------------------------------------
# 3. ОПРЕДЕЛЕНИЕ ВИДА ТРЕУГОЛЬНИКА
# --------------------------------------------------------------------------

def classify_triangle(a: float, b: float, c: float) -> str:
    """
    Возвращает один из вариантов:
    'равносторонний', 'равнобедренный', 'разносторонний', 'не треугольник'.
    Предполагается, что a, b, c уже являются положительными числами.
    """
    # неравенство треугольника: сумма любых двух сторон
    # должна быть строго больше третьей
    if (a + b <= c) or (a + c <= b) or (b + c <= a):
        return "не треугольник"

    if a == b == c:
        return "равносторонний"

    if a == b or b == c or a == c:
        return "равнобедренный"

    return "разносторонний"


# --------------------------------------------------------------------------
# 4. ВЫЧИСЛЕНИЕ КООРДИНАТ ВЕРШИН
# --------------------------------------------------------------------------

def compute_vertices(a: float, b: float, c: float):
    """
    Вычисляет координаты трёх вершин треугольника со сторонами a, b, c
    для отрисовки в поле 100x100 px.

    Первая вершина всегда в (0, 0), вторая — на оси X в (a, 0).
    Третья вершина находится через теорему косинусов и вписывается
    в поле 100x100 с помощью масштабирования.
    """
    # угол при вершине A (между сторонами b и c), по теореме косинусов
    cos_angle = (a ** 2 + b ** 2 - c ** 2) / (2 * a * b)
    # защита от погрешностей float (значение может выйти за [-1, 1]
    # на долю процента из-за округления)
    cos_angle = max(-1.0, min(1.0, cos_angle))
    angle = math.acos(cos_angle)

    p1 = (0.0, 0.0)
    p2 = (a, 0.0)
    p3 = (b * math.cos(angle), b * math.sin(angle))

    points = [p1, p2, p3]

    # масштабируем все точки, чтобы они поместились в поле 100x100 px
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    width = max(xs) - min(xs)
    height = max(ys) - min(ys)
    max_dimension = max(width, height, 1e-9)  # защита от деления на 0

    scale = 90 / max_dimension  # оставляем небольшой отступ от края (90 из 100 px)
    min_x, min_y = min(xs), min(ys)

    scaled_points = [
        (
            int(round((p[0] - min_x) * scale)) + 5,  # +5 px отступ от края
            int(round((p[1] - min_y) * scale)) + 5,
        )
        for p in points
    ]

    return scaled_points


# --------------------------------------------------------------------------
# 5. ГЛАВНАЯ ФУНКЦИЯ
# --------------------------------------------------------------------------

def analyze_triangle(side1: str, side2: str, side3: str):
    """
    Определяет вид треугольника по трём строкам-сторонам и вычисляет
    координаты вершин.

    Возвращает кортеж (тип: str, координаты: list[tuple[int, int]]).
    """
    logging.debug(
        f"Запрос на анализ треугольника: "
        f"side1={side1!r}, side2={side2!r}, side3={side3!r}"
    )

    try:
        a = parse_side(side1)
        b = parse_side(side2)
        c = parse_side(side3)

        # невалидные (нечисловые) данные
        if a is None or b is None or c is None:
            reason = "Одна или несколько сторон не являются числами"
            logging.error(
                f"Анализ треугольника не удался: {reason} "
                f"(side1={side1!r}, side2={side2!r}, side3={side3!r})"
            )
            return "", [(-2, -2), (-2, -2), (-2, -2)]

        # ошибочные числовые данные: стороны должны быть положительными
        if a <= 0 or b <= 0 or c <= 0:
            reason = "Стороны треугольника должны быть положительными числами"
            logging.error(
                f"Анализ треугольника не удался: {reason} (a={a}, b={b}, c={c})"
            )
            return "не треугольник", [(-1, -1), (-1, -1), (-1, -1)]

        triangle_type = classify_triangle(a, b, c)

        if triangle_type == "не треугольник":
            logging.error(
                f"Стороны a={a}, b={b}, c={c} не образуют треугольник "
                f"(нарушено неравенство треугольника)"
            )
            return triangle_type, [(-1, -1), (-1, -1), (-1, -1)]

        vertices = compute_vertices(a, b, c)
        logging.info(
            f"Анализ успешен: a={a}, b={b}, c={c} -> "
            f"тип={triangle_type}, вершины={vertices}"
        )
        return triangle_type, vertices

    except Exception:
        logging.exception(
            f"Непредвиденная ошибка при анализе треугольника "
            f"(side1={side1!r}, side2={side2!r}, side3={side3!r})"
        )
        return "", [(-2, -2), (-2, -2), (-2, -2)]


# --------------------------------------------------------------------------
# 6. ТОЧКА ВХОДА
# --------------------------------------------------------------------------

def main():
    setup_logging()
    logging.info("Логгер успешно сконфигурирован")
    logging.info("Приложение запущено")

    test_cases = [
        ("3", "3", "3"),        # равносторонний
        ("3", "3", "5"),        # равнобедренный
        ("3", "4", "5"),        # разносторонний
        ("1", "1", "10"),       # не треугольник (неравенство треугольника)
        ("-1", "2", "2"),       # отрицательная сторона
        ("abc", "2", "2"),      # нечисловые данные
    ]

    for side1, side2, side3 in test_cases:
        triangle_type, vertices = analyze_triangle(side1, side2, side3)
        print(f"({side1!r}, {side2!r}, {side3!r}) -> тип={triangle_type!r}, вершины={vertices}")

    logging.info("Приложение завершило работу")


if __name__ == "__main__":
    main()